import type { AIRequestOptions, AIResponseInfo, OperationOutcome } from '../shared';

/** Topic extracted from a note's content via AI analysis. */
export interface ExtractedTopic {
	/** Note-title-worthy name */
	title: string;
	/** One-sentence scope description */
	description: string;
	/** Relevance confidence (0-1) */
	relevance: number;
	/** Whether a vault note with this title already exists */
	existsInVault: boolean;
	/** Path of the existing note, if any */
	existingPath?: string;
	/** URLs from the source note related to this topic */
	relatedUrls: string[];
}

/** Local heuristic score to decide whether to recurse deeper. */
export interface QualityScore {
	/** Overall score (0-1); below threshold stops recursion */
	score: number;
	/** Number of child topics extracted */
	topicCount: number;
	/** Word count of the generated content */
	wordCount: number;
	/** True if the title is too generic (1-word or common term) */
	isTooGeneric: boolean;
	/** True if most child topics overlap with ancestors */
	hasHighOverlap: boolean;
	/** Human-readable explanation of the score */
	reasoning: string;
}

/** Status of a deep dive proposal. */
export type DeepDiveProposalStatus = 'pending' | 'accepted' | 'rejected';

/** A single proposed child note generated by deep dive. */
export interface DeepDiveProposal {
	id: string;
	/** ID of the DeepDiveRun this belongs to */
	runId: string;
	/** Path of the note this was extracted from */
	sourceNotePath: string;
	/** The topic that was extracted */
	topic: ExtractedTopic;
	/** Where the new note would be created */
	proposedPath: string;
	/** Full markdown content for the new note */
	proposedContent: string;
	/** Depth in the tree (0 = direct child of root) */
	depth: number;
	/** Quality score from local heuristic */
	qualityScore: QualityScore;
	/** IDs of proposals generated from this note */
	childProposalIds: string[];
	createdAt: string;
	status: DeepDiveProposalStatus;
	/** How the note's text was produced: provider, model, stop reason, usage (#625). Absent on proposals saved before it. */
	generation?: AIResponseInfo;
}

/** Status of a deep dive run. */
export type DeepDiveRunStatus = 'in-progress' | 'completed' | 'cancelled';

/**
 * Why a run's generation loop last ended (#625): `cap` = the note cap was reached with topics left
 * (kept in `pending`, see `DeepDiveModule.continueRun`); `exhausted` = no topics left; `cancelled`;
 * `error` = interrupted, resumable from its checkpoint.
 */
export type DeepDiveEndReason = 'cap' | 'exhausted' | 'cancelled' | 'error';

/** Metadata for one invocation of the deep dive command. */
export interface DeepDiveRun {
	id: string;
	/** Root note that started the dive */
	rootNotePath: string;
	/** Max depth configured for this run */
	maxDepth: number;
	/** Quality threshold configured for this run */
	qualityThreshold: number;
	/** All proposal IDs in this run */
	proposalIds: string[];
	stats: {
		totalProposals: number;
		byDepth: Record<number, number>;
		earlyTerminations: number;
	};
	createdAt: string;
	status: DeepDiveRunStatus;
	/** Why generation last ended; absent while running and on runs saved before #625. */
	endReason?: DeepDiveEndReason;
	/** Unfinished generation work: kept so an interrupted run resumes from its checkpoint, and a capped run can continue. */
	pending?: DeepDivePendingWork;
	/** Per-run note cap from `DeepDiveModule.run`; absent = `deepDive.maxNotesPerRun`. */
	maxNotes?: number;
	/** Per-run auto-accept from `DeepDiveModule.run`; absent = `autoAccept['deep-dive']`. */
	autoAccept?: boolean;
}

/** Answers the depth picker and confirm modal would ask for, so a run can start without UI. */
export interface DeepDiveRunOptions {
	/** Recursion depth; default `deepDive.maxDepth`, clamped to the picker's 1-6. */
	depth?: number;
	/** Note cap for this run; default `deepDive.maxNotesPerRun`. */
	maxNotes?: number;
	/** Accept every generated note when the run finishes; default `autoAccept['deep-dive']`. */
	autoAccept?: boolean;
	/** Public-API job running this deep dive (#624); its operations are tagged with `jobOpId`. Not persisted. */
	jobId?: string;
}

/** What a deep-dive run, or a regeneration, did: proposals created (run) or rewritten (regenerate), notes written. */
export interface DeepDiveOutcome extends OperationOutcome {
	runId?: string;
	/** Set when generation ran (`run`, `continueRun`). */
	endReason?: DeepDiveEndReason;
	/** Topics still queued when the run hit its cap; `continueRun` generates them. */
	remainingTopics?: number;
}

/** A capped run that can be continued (#625). */
export interface ContinuableDeepDiveRun {
	runId: string;
	rootNotePath: string;
	/** Topics left in the queue. */
	remainingTopics: number;
	/** Proposals the run has generated so far. */
	totalProposals: number;
	createdAt: string;
}

/** `regenerate` target: a proposal id, or the path of the note a proposal created. */
export type DeepDiveRegenerateTarget = { proposalId: string } | { notePath: string };

/** One topic still to generate; its source is the root note, or the parent proposal when set. */
export interface DeepDiveTask {
	topic: ExtractedTopic;
	depth: number;
	ancestorTopics: string[];
	parentProposalId?: string;
}

/** Breadth-first generation queue persisted after every generated proposal. */
export interface DeepDivePendingWork {
	tasks: DeepDiveTask[];
	processedCount: number;
}

/** Existing-folder suggestion for a topic title from the organize engine; wired by the module registry so deep-dive never imports organize. */
export type SuggestDirectory = (text: string, aiOpts?: AIRequestOptions) => Promise<string | null>;

/**
 * A node in the depth-first traversal of accepted proposals.
 * Used to compute prev/next/up/root relationships.
 */
export interface TraversalNode {
	proposalId: string;
	title: string;
	proposedPath: string;
	depth: number;
	/** Index in the DFS order (0-based) */
	index: number;
	/** Parent proposal ID (null for root-level proposals) */
	parentId: string | null;
	/** Child proposal IDs that are accepted */
	childIds: string[];
}

/**
 * Navigation context for a single accepted proposal.
 */
export interface NavigationContext {
	/** Root note title and path */
	root: { title: string; path: string };
	/** Parent proposal (null for depth-0 proposals) */
	up: { title: string; path: string } | null;
	/** Previous proposal in DFS order (null for first) */
	prev: { title: string; path: string } | null;
	/** Next proposal in DFS order (null for last) */
	next: { title: string; path: string } | null;
	/** 1-based position in the traversal */
	position: number;
	/** Total accepted proposals */
	total: number;
	/** Breadcrumb path from root: ["Machine Learning", "Neural Networks", "Backpropagation"] */
	breadcrumbs: string[];
	/** Title and path of the syllabus note */
	syllabus: { title: string; path: string };
}
